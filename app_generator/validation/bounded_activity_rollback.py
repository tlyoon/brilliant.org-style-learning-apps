"""Fail-closed rollback of a known injected scientific contradiction.

Only appended, explicitly detected scope contradictions in one previously
source/physics-bounded localized option are eligible. Not generative repair and
not academic PASS. Unknown content changes must be reviewed separately.
"""
from __future__ import annotations

from copy import deepcopy
from hashlib import sha256
import json
from pathlib import Path
from typing import Any

from app_generator.validation.impulse_qualifier_repair import ACTIVITY_ID
from app_generator.validation.impulse_v3_audit import ITEM_ID, net_impulse_scope_conflicts
from app_generator.validation.source_bound_defect_routing import (
    LOCALES, route_source_bound_defect,
)

MAX_APPENDED_CHARS=240


def restore_known_bounded_version(
    *, candidate_file: Path, baseline_file: Path, source_pdf: Path,
    baseline_dossier_file: Path, expected_baseline_sha256: str,
    expected_source_sha256: str, private_output_dir: Path,
) -> dict[str, Any]:
    original=baseline_file.read_bytes()
    corrupted=candidate_file.read_bytes()
    original_sha=sha256(original).hexdigest()
    corrupt_sha=sha256(corrupted).hexdigest()
    if original_sha != expected_baseline_sha256 or original_sha == corrupt_sha:
        raise ValueError("known evidence-bound baseline absent or no defective revision")
    source_bytes=source_pdf.read_bytes()
    if source_bytes[:5] != b"%PDF-" or sha256(source_bytes).hexdigest()!=expected_source_sha256:
        raise ValueError("original textbook source PDF differs")
    baseline=json.loads(original)
    candidate=json.loads(corrupted)
    if not isinstance(baseline.get("activities"),list) or not isinstance(candidate.get("activities"),list):
        raise ValueError("activity lists absent")
    old=[a for a in baseline["activities"] if isinstance(a,dict) and a.get("id")==ACTIVITY_ID]
    new=[a for a in candidate["activities"] if isinstance(a,dict) and a.get("id")==ACTIVITY_ID]
    if len(old)!=1 or len(new)!=1:
        raise ValueError("original target activity missing or duplicated")
    old_items=old[0].get("interaction",{}).get("items",[])
    new_items=new[0].get("interaction",{}).get("items",[])
    if not isinstance(old_items,list) or not isinstance(new_items,list):
        raise ValueError("invalid option structure")
    matched=[(i,x) for i,x in enumerate(old_items) if isinstance(x,dict) and x.get("id")==ITEM_ID]
    if len(matched)!=1 or len(new_items)<=matched[0][0]:
        raise ValueError("known evidence-bound option missing")
    idx=matched[0][0]
    old_label=old_items[idx].get("label")
    new_label=new_items[idx].get("label")
    if not isinstance(old_label,dict) or not isinstance(new_label,dict) or set(new_label)!=set(old_label):
        raise ValueError("localized option structure changed")
    edits=[]
    for language in LOCALES:
        before=old_label.get(language)
        after=new_label.get(language)
        if not isinstance(before,str) or not isinstance(after,str):
            raise ValueError("localized original option missing")
        if before == after:
            continue
        extra=after[len(before):] if after.startswith(before) else ""
        conflicts=net_impulse_scope_conflicts(extra,language)
        if not extra.strip() or len(extra)>MAX_APPENDED_CHARS or not conflicts:
            raise ValueError("unrecognized or nonappend-only change cannot be auto-restored")
        edits.append({"language":language,"contradictionCodes":conflicts})
    if not edits:
        raise ValueError("no independently detectable scientific contradiction")
    # Confirm EXACTLY these localized text appendages changed in the whole
    # package. Any changed key, other answer, diagram or activity fails closed.
    reconstructed=deepcopy(candidate)
    reconstructed["activities"]=[
        (a if a.get("id")!=ACTIVITY_ID else deepcopy(a))
        for a in reconstructed["activities"]
    ]
    repaired_activity=next(a for a in reconstructed["activities"] if a["id"]==ACTIVITY_ID)
    repaired_activity["interaction"]["items"][idx]["label"]=deepcopy(old_label)
    if reconstructed!=baseline:
        raise ValueError("unrelated package field, answer or other activity changed")
    # Freshly invoke the exact-version private evidence check on the BASELINE,
    # never on a forgery generated by mutating only public receipt hashes.
    decision=route_source_bound_defect(
        package_file=baseline_file,source_pdf=source_pdf,
        dossier_file=baseline_dossier_file,
        expected_package_sha256=expected_baseline_sha256,
        expected_source_sha256=expected_source_sha256,
    )
    if decision["nextAction"]!="AUTO_INDEPENDENT_SEMANTIC_VISUAL_REVIEW":
        raise ValueError("previous bounded baseline itself has unresolved contradictions")
    target=private_output_dir.resolve()
    root=Path(__file__).resolve().parents[2]
    if target.is_relative_to(root) or target.exists():
        raise ValueError("private repair output must be new and outside Git")
    result={
        "activityId":ACTIVITY_ID,
        "sourceSha256":expected_source_sha256,
        "defectivePackageSha256":corrupt_sha,
        "restoredPackageSha256":original_sha,
        "detectedContradictions":edits,
        "restoration":"EXACT_KNOWN_BOUNDED_BASELINE",
        "independentBoundedRecheck":"MATCHED",
        "nextAction":"AUTO_INDEPENDENT_SEMANTIC_VISUAL_REVIEW",
        "independentReverificationRequired":True,
        "fullAcademicPass":False,
        "academicQA":"REVIEW_REQUIRED",
        "publicationAuthorized":False,
    }
    target.mkdir(parents=True,exist_ok=False)
    restored=target/"restored-package.json"
    with restored.open("xb") as stream:
        stream.write(original)
    with (target/"revalidation.json").open("x",encoding="utf-8") as stream:
        json.dump(result,stream,indent=2,ensure_ascii=True)
        stream.write("\n")
    if sha256(restored.read_bytes()).hexdigest()!=original_sha:
        raise ValueError("restored private package bytes differ")
    # No automatic installation or publication, even after bounded recovery.
    return result